// Ethnographic model of the Balkans, c. 1878.
//
// This is an original, simplified reconstruction for a game, NOT a scholarly
// dataset. Each regional anchor gives an approximate population density
// (people/km²) and ethnic mix; the game interpolates between anchors.
// Cities are added on top as local population bumps.
//
// Mixes were compiled from:
//  - Austro-Hungarian census of Bosnia-Herzegovina, 1879 (42.9% Orthodox,
//    38.7% Muslim, 18.1% Catholic)
//  - Hungarian census of 1880 (Transylvania: 57% Romanian, 25.9% Hungarian,
//    12.5% German)
//  - Eastern Rumelian census of 1880 (~70% Bulgarian, ~21% Turkish, ~5% Greek)
//  - Romanian statistics for Northern Dobruja, 1878–80
//  - Ottoman census of 1881/82–1893 (e.g. Sanjak of Monastir: 49.8% Bulgarian
//    Exarchists, 26.7% Muslim, 22.2% Patriarchist Greeks, 1.3% Jewish)
//  - Ottoman figures for Thessaly, 1877/8 (~285k Greeks, 40k Turks, 40k Jews)
//  - The ethnographic maps of Kiepert (1876, 1878), Synvet (1877) and
//    Stanford (1877), as discussed in "Ethnographic cartography of the Balkans
//    in the late 19th and early 20th century" (Wikipedia).
//
// Period sources disagree sharply, above all about Macedonia, Thrace, Epirus
// and Kosovo. Where they do, this model picks a middle reading, and the game's
// About panel says so. "Macedonian Slavs" is used as a neutral label: in 1878
// most were counted as Bulgarians (Exarchists), while Serbian and Greek
// sources claimed many of them.

